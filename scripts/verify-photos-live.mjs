import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const base='https://disorder119.github.io/flink-aschaffenburg-chat-projekt/';
const photos=JSON.parse(await readFile('src/data/photos.json','utf8'));
const workflow=JSON.parse(await readFile('qa/upgrade-workflow.json','utf8'));
if(workflow.status!=='completed'||workflow.conclusion!=='success')throw new Error('Workflow not confirmed successful');
const localIndex=await readFile('dist/index.html','utf8');
const remote=await fetch(base,{signal:AbortSignal.timeout(20000)});
const html=await remote.text();
if(!remote.ok)throw new Error('Live index HTTP '+remote.status);
const expectedAssets=[...localIndex.matchAll(/(?:src|href)="([^"]+\.(?:js|css))"/g)].map(m=>m[1]);
if(expectedAssets.some(asset=>!html.includes(asset)))throw new Error('Live HTML does not reference current build assets');
const sha=body=>createHash('sha256').update(body).digest('hex');
const results=await Promise.all(Object.entries(photos).map(async ([id,p])=>{
 const url=base+'product-images/'+p.file;
 const r=await fetch(url,{signal:AbortSignal.timeout(20000)});
 const body=Buffer.from(await r.arrayBuffer());
 const identical=sha(body)===sha(await readFile('public/product-images/'+p.file));
 if(!r.ok||!r.headers.get('content-type')?.startsWith('image/')||!identical)throw new Error(`Photo ${id}: live verification failed, HTTP ${r.status}`);
 return {id,url,status:r.status,bytes:body.length,mime:r.headers.get('content-type'),matchesLocalFile:identical};
}));
const report={checkedAt:new Date().toISOString(),url:base,https:true,indexStatus:remote.status,buildAssetsMatch:true,workflow:{url:workflow.url,commit:workflow.headSha,status:workflow.status,conclusion:workflow.conclusion,jobs:workflow.jobs.map(j=>({name:j.name,conclusion:j.conclusion}))},photos:results,note:'Browser rendering separately documented in UPGRADE-2026-10-12.md.'};
await writeFile('qa/upgrade-deployment.json',JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report,null,2));
